const assert=require('node:assert/strict');
const v=require('./live_view.js');
assert.equal(v.probability(73.5),'73.5% · score 73.5/100');
for(const score of [null,undefined,NaN,-1,101,'80'])assert.equal(v.probability(score),'Unavailable');
assert.equal(v.probability(80,false),'Unavailable');
const now=Date.parse('2026-09-18T05:30:00Z');
assert(v.recent('2026-09-18T05:30:00Z',now));
assert(!v.recent('2026-09-18T05:29:29Z',now));
assert(!v.recent('2026-09-18T05:30:01Z',now));
assert(v.forecast({checkpoints:[]},null,now).includes('No valid projected path'));
const a={name:'NIFTY',checkpoints:[{target_at:'2026-09-18T05:35:00Z',low:99,expected:100,high:101},{target_at:'2026-09-18T05:40:00Z',low:100,expected:102,high:103}]};
const chart=v.forecast(a,{last_updated:'2026-09-18T05:30:00Z',technicals:{vwap:100,ema20:101}},now);
assert(chart.includes('11:05'));assert(chart.includes('11:10'));assert(chart.includes('VWAP 100'));assert(!chart.includes('NaN'));
assert(!v.forecast({...a,name:'<script>alert(1)</script>'},null,now).includes('<script>'));
const data={sources:[{name:'NSE',status:'ok',checked_at:'2026-09-18T05:30:00Z'}],articles:[{title:'<img onerror="x">',url:'javascript:alert(1)'}]};
assert(v.news(data,true,now).includes('CHECK CONNECTED'));
assert(v.news(data,true,now+151000).includes('UNAVAILABLE / LAST KNOWN'));
assert(v.news(data,false,now).includes('UNAVAILABLE / LAST KNOWN'));
assert(!v.news(data,true,now).includes('javascript:'));
assert(!v.news(data,true,now).includes('<img'));
console.log('Score mapping, stale/future quotes, timestamped paths and safe news rendering passed');
